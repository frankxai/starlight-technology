const OWNER = "starlight.technology/editorial";
const V = "1.0.0";
const OBSERVED = "2026-09-02";

function claim<T>(
  value: T,
  evidenceKind: EvidenceKind,
  source: string,
  options: { region?: Region; observedAt?: string; note?: string } = {},
): Claim<T> {
  return {
    value,
    evidenceKind,
    source,
    observedAt: options.observedAt ?? OBSERVED,
    region: options.region ?? "GLOBAL",
    note: options.note,
  };
}

function source(
  id: string,
  publisher: string,
  title: string,
  url: string,
  standing: EvidenceSourceNode["standing"],
): EvidenceSourceNode {
  return {
    id,
    kind: "EvidenceSource",
    label: `${publisher} — ${title}`,
    owner: OWNER,
    provenance: `retrieved ${OBSERVED}`,
    version: V,
    visibility: "public",
    evaluationRule: "Re-fetch on review; if the page no longer states the cited value, every claim citing it is void.",
    publisher,
    title,
    url,
    retrievedAt: OBSERVED,
    standing,
  };
}

function price(
  id: string,
  subjectId: string,
  sourceId: string,
  amountMinor: number | null,
  currency: "EUR" | "USD",
  region: Region,
  basis: PriceObservationNode["basis"],
  note: string,
): PriceObservationNode {
  return {
    id,
    kind: "PriceObservation",
    label: note,
    owner: OWNER,
    provenance: basis === "unverified" ? "not observed in this session" : `cited from ${sourceId}`,
    version: V,
    visibility: "public",
    evaluationRule: "Stale after 30 days. A stale or unverified price cannot support a live recommendation.",
    subjectId,
    basis,
    currency,
    amountMinor,
    observedAt: OBSERVED,
    region,
    sourceId,
  };
}

